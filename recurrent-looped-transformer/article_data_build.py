t("时间反馈方面，Feedback Transformer 把已处理的历史表示提供给未来计算，Recurrent Transformer 从各层输出构建该层持久 KV 并通过精确分块调度改善内存搬运；RLT 则是把前一个最终解码器输出反馈到下一个解码器输入，其全局注意力记忆源自编码器、局部 SWA 键值源自解码器，提示词与响应都承载递归。区别在于反馈位置与记忆表示，而不是声称预填充完全并行。沿深度复用方面，Universal Transformers 沿深度共享计算，递归深度潜在推理通过迭代递归模块扩展计算量；RLT 的状态跨 token 推进，权重绑定配置还额外共享兼容的编码器与解码器权重——单独的权重绑定或时间递归本身，都不足以确立新颖性或质量提升。")
