h2("方法：一条贯穿提示词与响应的状态转移")
h3("序列与状态")
t("设 x(1:S) 是一个独立序列，且 x1 为 BOS。推理时 x(1:T) 是已观测提示词，之后的 token 构成续写；索引 T 标记服务边界，并不表示条件模型发生改变。记 LE、LD 分别为编码器与解码器深度，d 为残差流宽度。编码器表示为 e(t)，递归输出为 s(t)。完整解码器状态是 H(t) = (s(t), CD(t))，其中 CD(t) 包含各解码器滑动窗口注意力（SWA）层保留的键值投影，窗口大小为 W，包含当前 token，每次更新后每层缓存至多保留 W−1 个位置供下一次更新使用。所有参数（包括可学习的初始状态 s⋆）统记为 Θ，Eθ 与 Dφ 分别表示编码器与解码器部分。")

h3("因果编码器与记忆")
t("对已观测前缀计算编码器表示 e(1:T) = Eθ(x(1:T))。借助因果掩码，同一编码器层内的各个位置可以同时处理，但层与层之间仍按顺序计算。对解码器记忆组 g，键值记忆由编码器表示投影得到：k(g,t) = PK(g)(e(t), t)，v(g,t) = WV(g)·RMSNormE(e(t))，记忆 M(≤t) 由前缀内所有键值对组成。")
t("键映射包含归一化、投影与所采用的位置变换；解码器第 ℓ 层读取记忆组 g(ℓ)。组数 G = 1 表示跨层共享记忆，G = 等于解码器层数则允许逐层使用不同投影。这份全局记忆依赖编码器表示，而不是解码器状态。参考解码器把针对该记忆的交叉注意力与针对解码器激活的因果 SWA 结合：两种存储承担不同角色，M(≤t) 提供全局编码器上下文，CD(t) 提供有界窗口内源自解码器的键值。")

h3("每个 token 使用同一状态转移")
t("状态只在 BOS 之前初始化一次：H(0) = (s⋆, 空集)。对每一个已观测或采样的 token 执行同一个转移：先做合并 u(t) = Merge(e(t), s(t−1))；再计算 H(t) = (s(t), CD(t)) = Dφ(u(t); M(≤t), CD(t−1), t)；最后由 s(t) 经归一化与输出投影的 softmax 得到下一个 token 的分布。")
t("对固定 token 序列，编码器特征不直接依赖解码器状态，但用于预测首个响应 token 的完整状态包含了全部提示词转移，也就是一串嵌套的转移函数复合。生成从该状态继续：从 s(T) 采样出下一个 token 后，对它做增量编码、追加源自编码器的键值，并计算新状态，其中包含所有解码器 SWA 缓存的更新。服务边界处不会重置状态的任何一个分量。")

h3("提示词预填充与增量解码")
t("预填充（prefill）先计算提示词的因果编码器表示与记忆，然后依次计算各步状态。即使完整提示词记忆已经可用，解码器在位置 t 的注意力仍被限制在 M(≤t) 之内。生成阶段用编码器缓存执行单步编码，随后追加记忆并执行同一套解码器转移。已观测 token 可以分块编码，但必须保留因果编码器缓存，且每个 token 仍须执行其解码器更新。")
t("并行编码器处理与逐步递归编码，是同一因果计算的不同执行调度；对非线性解码器递归，报告不假设存在对应的常规全并行调度。特别地，历史解码器键值必须由此前的递归更新生成，标准的并行 SWA 解码器遍历通常并不等价。")

h3("合并操作与解码器模块")
t("一种具体的门控合并形式是：先对上一状态做 RMSNorm 得到 r；门控 g 由输入编码器表示与该状态拼接后经 sigmoid 得到；合并结果等于编码器表示加上按反馈尺度 α 缩放的、门控与状态投影逐元素相乘的结果。其中 α 控制反馈尺度，报告指出「较小的非零初始反馈尺度」只是一种候选初始化方式，并非已经确立的稳定性方案；使用标量门控或低秩投影可以降低开销。")
t("解码器模块依次执行因果 SWA、编码器记忆交叉注意力与 FFN，每步都带残差与归一化。注意力算子本身包含输出投影，查询与键映射包含各自的归一化与位置变换。在每一层，当前键值都在 SWA 之前由该层输入构建，因此对当前位置的注意力不会引入循环依赖；历史解码器键值来自上一步的状态。更新后只保留窗口内的位置，窗口为 1 时该集合为空。预填充、采样与回放使用相同的位置元数据约定；其他子层顺序会定义不同变体，必须在所有执行模式下保持一致。")
fig("fig01.png","图 1：贯穿提示词与响应的统一递归计算。编码器构建因果 KV 记忆，解码器按顺序处理每一个 token；完整解码器状态跨越提示词与响应边界传递而不重置")

h3("循环在哪里：一种具体的权重绑定配置")
t("参考的权重绑定配置取编码器与解码器层数相同。编码器第 ℓ 层的自注意力与解码器第 ℓ 层的 SWA 共享兼容的查询、键、值与输出投影矩阵，两者的 FFN 也共享；编码器使用自身的因果上下文，解码器 SWA 则使用窗口内的解码器激活。解码器交叉注意力拥有独立的查询与输出投影，以及记忆投影。各阶段专属的归一化、合并与读出仍是显式模块。")
t("因此，解码器模块是在复用的注意力与 FFN 核心之上增加交叉注意力；两次逻辑遍历并不意味着每个模块的浮点运算量相等。这是在不同注意力连接方式下复用参数，而不是复制激活，任何解码器输出都不被等同于编码器输出。若不做权重绑定，完整状态递归依然保留，只是取消了沿深度的参数复用；编码器记忆组的共享则是另一个独立维度，既不会合并也不会消除逐层的解码器 SWA 缓存。")

h2("计算性质")
h3("对服务分割位置的不变性")
t("报告给出的第一个命题是：固定参数、token 序列、位置约定与独立序列初始状态，并假设因果编码器执行在数学上等价、SWA 窗口与缓存更新相同、解码器操作确定，那么对任意前缀「先批量编码器预填充、再递归解码器更新」与「逐 token 增量处理」，会得到相同的状态与下一个 token 分布。换句话说，对固定的 token 历史，移动提示词与响应的分割位置不会改变条件分布。")
t("证明的思路是归纳：因果编码器的等价性保证两种调度得到相同的编码器表示与记忆；两者都从同一初始状态出发；若在 t−1 时状态相同，那么第 t 步对相同输入执行相同操作，状态仍相同。服务分割位置从未出现在转移公式中。")
t("需要强调的是，这只是在数学意义上的等价：不同内核与精度选择仍可能带来数值差异；该结论也假设分词与上下文一致，且任一执行过程中都没有丢弃 token、重置状态或插入过时状态。")

h3("预填充计算量与顺序深度")
t("把编码器预填充计算量、记忆投影计算量与单步解码器计算量相加，就得到总预填充计算量。对稠密注意力以及与模型宽度成正比的键值宽度，粗略的算术复杂度与传统稠密 Transformer 同阶：编码器与解码器项、记忆投影项，加上解码器在受限窗口上的项。")
t("关键差异不在阶数，而在顺序性：解码器存在一条经过 T 次转移的顺序路径，每次转移包含 LD 个模块。因此编码器可以并行，并不意味着整个模型的预填充完全并行；即使算术复杂度阶数相同，状态递归仍可能降低硬件利用率。报告明确表示接受这一成本以保留完整提示词计算，也不声称通过减少预填充计算获得加速。")
t("此外，每个新 token 要执行 LE 加 LD 个模块，还要加上合并与记忆投影的开销，而注意力计算量仍随上下文长度增长。推理缓存存储量约由三部分构成：编码器侧随层数与记忆组数增长的部分、解码器 SWA 保留的历史（与窗口大小取较小值）、以及当前递归输出。参数绑定能减少权重存储，但既不会消除第二次逻辑遍历，也不会消除任何一种缓存的作用。")

h3("具有无限时间深度的潜在推理")
t("到位置 t 为止的可用状态路径复合了 t 次解码器转移，从序列起点穿过 t 倍解码器层数的模块；对长度为 T 的提示词与随后 n 个已处理续写 token，路径包含 (T+n) 倍解码器层数的模块。这个深度包含提示词，并随已处理历史增长，而每个 token 的模块数量保持固定。")
t("报告也给出了必要的保留：门控、收缩效应与可学习投影可能抑制长路径的实际贡献，结构深度本身并不保证推理能力；图中的计数是解析计数，不含合并与读出，衡量的是结构深度，而不是有效推理质量或实际耗时。")
