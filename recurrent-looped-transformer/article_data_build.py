h3("内存访问与参数复用")
t("对固定的 token 前缀与参数集，源自编码器的键值不再变化：解码器层读取这部分记忆，同时把源自解码器的键值追加到各层有界的 SWA 缓存里，这些缓存不能被编码器记忆替代。共享记忆组可以减少键值存储与投影，而使用更多记忆组则保留逐层不同的记忆变换。绑定兼容的编码器与解码器权重可以减少参数存储、并可能有利于权重常驻，但它本身并不减少模块的计算次数，也不保证更低延迟。")
