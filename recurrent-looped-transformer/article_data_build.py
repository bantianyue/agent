h3("训练内存与执行保真度")
t("激活检查点以重计算换取更少的激活存储，同时保留完整的时间反向传播（BPTT）。编码器批处理、跨样本解码器批处理与检查点位置，应当结合序列长度与加速器内存共同选择。优化目标是在参考递归计算下获得有效的训练与推理吞吐量，而不是通过近似把递归消除掉。")
t("报告引用了另一项工作对「实际执行策略」的界定：它既取决于权重，也取决于精度、缓存构建、归约与采样变换等执行选择。硬件与算法选择在「回放保真度」处交汇：内核精度、随机操作、位置约定与缓存生命周期必须与被评估的策略一致。完整提示词递归确实产生额外成本，协同设计的目的是高效执行这些计算——在拿到测量结果之前，硬件高效的训练与推理仍然只是工程目标。")

h2("训练目标")
h3("自回归预训练")
t("基础目标是全序列的下一 token 预测损失：在初始状态展开完整的解码器状态转移，对位置 1 到 S−1 的每个非 BOS 目标都施加监督，编码器、记忆投影、合并模块与解码器联合训练。独立文档会重置递归输出、解码器 SWA 缓存、编码器缓存与位置，并使用彼此隔离的注意力掩码。报告特别提醒：必须使用完整文档，或者明确声明初始上下文约定的片段；不能在切分片段时悄然丢弃状态，却仍声称计算了完整历史似然。")

h3("监督微调")
t("在 SFT 中，对助手目标令掩码为 1，对用户、系统、工具或填充目标令其为 0，只对至少有一个选中目标的样本计算损失。关键细节是：损失掩码不屏蔽状态更新，也不分离编码器记忆、递归输出或解码器键值的梯度。也就是说，解码器处理所有先前上下文 token（包括用户与工具消息），助手损失的梯度可以流经这些提示词计算；状态不在助手边界重置，也不需要额外的边界适配目标来修补提示词专属的转移变化。")

h3("模型与 RL 算法协同设计")
t("策略定义为响应各 token 条件概率的乘积，目标是在给定提示词下最大化期望奖励。其同策略得分函数梯度形如「（奖励减去与响应无关的基线）× 各 token 对数概率梯度之和」；对数概率回放期间离散采样 token 保持固定，但求导包含其连续的递归计算。报告强调，架构不要求特定的奖励函数、裁剪规则或 KL 正则项。")
