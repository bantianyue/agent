h2("模型与硬件协同设计")
h3("围绕递归核心的并行计算")
t("对于已知的训练序列或提示词，可以用 token 并行内核计算编码器特征与记忆投影，随后解码器遵循状态依赖执行。可以把独立序列中已就绪的解码器转移组成批次：每个序列贡献它的下一次状态更新，同时维护自己的编码器 KV 前缀、解码器 SWA 缓存、递归输出与位置。这提供了批次层面的并行性，但报告并不声称递归解码器内部存在序列层面的并行性。")
t("推理时，编码器单步计算、记忆追加、合并、解码器模块与读出形成重复的执行调度；联合调度独立请求可以增大矩阵运算规模、提高权重复用，但小批次或不均匀的序列长度可能限制利用率。报告也不假设一般非线性解码器存在精确的并行扫描。")
