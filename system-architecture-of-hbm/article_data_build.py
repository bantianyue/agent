h3("DRAM 的工作原理")
t("DRAM 用极省面积的 1T1C 单元存储数据：一个晶体管加一个电容。单元被充电到 VDD 时表示逻辑 1，空的时候表示逻辑 0。在现代 DRAM 节点中，电容通常做成高柱或沟槽介质，以最小化表面积，容量大致在 15 到 25 飞法之间；一个 NMOS 晶体管把电容连到 bitline 与 wordline 上。这些单元横向通过 wordline 连成阵列，一次 wordline 激活会同时访问这一行里的所有单元；纵向则通过 bitline 连到感放器（sense amplifier），数据从那里读出。")
fig("fig06.png","一个带晶体管与电容的 DRAM 单元")
t("读操作分几步发生：先把 bitline 预充并稳定到中间电位（电源电压的一半）；然后断开 bitline 与电源的连接、把选中的 wordline 拉高，电荷在单元电容与悬空的 bitline 电容之间重新分配。注意 bitline 电容通常比单元电容大 10 到 20 倍，由于这个电容分压比，bitline 上感测到的电压非常小。接着感放器被激活，把电压读出来；需要强调，真正的「读取」过程本质上是破坏性的，因为电荷全都被消耗掉了。之后单元电荷通过感放器涌入的电流被刷新回来，bitline 需要一段最小刷新时间；刷新时间结束后，wordline 被驱回 0。")
