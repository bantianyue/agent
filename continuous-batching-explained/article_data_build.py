t("在传统的机器学习推理里，一个 batch 通常被表示成一个矩阵。")
t("如果输入长度各不相同，就把每个输入补齐或截断到同一长度，堆叠成一个张量，通过一次前向传播为每一行生成一个预测。在这种设定下，每一行的成本相同、结束时刻相同，整个工作量在开始之前就已知晓，这里的批处理本质上是一个张量打包问题。")
fig("fig01.jpg","图 1：长度不一的文本被补齐到同一宽度，从而堆叠成一个 batch 张量，每行对应一个标签")
t("LLM 的解码完全不按这套原则运作。在底层，一次前向传播只为每条序列生成一个 token，因此一个请求需要多少轮前向，取决于它要输出多少 token，而在模型吐出停止符之前，没人知道这个数量。")
fig("fig02.jpg","图 2：传统机器学习的 batch 是一个补齐矩阵，所有行同时结束；LLM 解码的 batch 则是一组在不同时刻停止的请求")
t("补齐解决不了这个问题，因为错配不在于输入宽度，而在于每个请求占用 GPU 的时间长度不同。于是一个在开始时固定的 batch，只能以最慢成员的速度前进。")
t("连续批处理正是为了绕开这个问题而出现在大多数推理引擎里的方案，vLLM、SGLang、TGI、TensorRT-LLM 都默认启用它。")
fig("fig03.jpg","图 3：连续批处理的全过程：请求排队进入，每个请求每轮生成一个 token，完成的请求离开、新请求加入 batch，GPU 因此保持满载")
t("它的核心思想是：把「决定 batch 成员」这件事从批处理开始时一次，改成每一次前向传播都重新决定；一个完成的请求在下一轮就离开，一个等待中的请求当场补进它的位置，于是没有任何一个槽位会为已经做完的工作白白保留。")
fig("fig04.png","图 4：批处理的时间线：横轴是轮次，每一行是一个请求；浅色方块是提示词 token，深色方块是生成 token，END 表示该序列结束")
t("支撑这套机制端到端运转的核心，就是连续批处理底下的那个调度器：它是在每一轮前向传播里决定「哪些请求拿到 token、各拿多少」的那个循环。下面从问题本身搭起，按顺序走完一个调度步骤，再看机制清楚之后的实测收益。")

h2("传统机器学习推理里的调度")
t("一个分类器接受定宽输入，返回一个标签；序列模型则补齐到最大长度、再把补齐部分掩掉。无论哪种方式，进去的张量形状已知，出来的张量行数与之匹配。")
t("之所以要做批处理，根本原因是：从 HBM 里加载模型权重，是每一轮前向传播的固定成本。因此，如果把 64 行输入堆进一次前向、让这 64 行共享同一次权重读取，吞吐就会上去。")
fig("fig05.jpg","图 5：批处理之所以划算，是因为最贵的部分（从 HBM 读取权重）只付一次，无论有多少行搭同一趟车")
t("在实践里提供服务也很直接：填满一个 batch、跑完它、返回所有结果、再开始下一个。没有任何请求会把状态带进下一轮前向，也没有任何请求会比它加入的那个 batch 活得更久。")

h2("LLM 推理的性质")
t("LLM 的解码过程打破了上面讨论的三个假设：每一轮前向对每条序列只生成一个 token；KV cache 会把状态带进下一轮前向；一个请求需要多少轮，只有在它产出停止符时才知道。")
t("于是，一个 30 个 token 就结束的请求，会和一个要跑到 400 的请求待在同一个 batch 里；在固定批处理下，它要为全部 400 步占着自己的槽位，却什么也不产出。GPU 为这个大部分空着的 batch 持续付出完整的权重读取成本。浪费的程度直接随输出长度的差异放大，而在真实流量里，这种差异可能相当大。")
fig("fig06.jpg","图 6：静态批处理 vs 连续批处理：静态情形下槽位空转，连续情形下槽位在下一轮迭代就被新请求补上")

h2("解法：迭代级调度与选择性批处理")
t("要解决这个问题，就得改变服务系统与执行引擎之间的对接方式。本质上，不再是把一个 batch 交出去、一直等到所有请求完成，而是让调度器只跑一轮迭代、拿回控制权、然后再决定一次。这被称为迭代级调度，它描述的正是连续批处理在底层使用的机制。")
fig("fig07.jpg","图 7：迭代级调度：连续三轮前向传播里，batch 的成员在不断变化")
t("一条完成的序列在下一个迭代边界离开，而不是等到整个批处理跑完；一个等待中的请求在同一个边界进入。batch 在每一轮前向传播里被重建。")
fig("fig08.png","图 8：迭代边界上的替换：一条序列结束后离开，等待中的请求在同一个边界进入并接管它的位置")
t("但这件事本身还不够，因为每轮重建 batch 会带来它自己的问题。比如一个正在 prefill 4,096 个 token 的请求，和一个正在解码第 900 个 token 的请求，它们并不共享同一张张量形状，没法按通常的方式堆在一起。选择性批处理解决了这一点：它确保批处理只施加在能够承受批处理的算子之上。")
t("在这一步里被调度的每一个 token，无论来自哪个请求，都会被展平成一整条形状为「总 token 数 × 隐藏维」的长序列。")
fig("fig09.jpg","图 9：除了注意力，其他算子都把一个 token 当作独立的个体，所以它们可以共用同一个 batch；注意力则只能让一个 token 读取它自己请求里的 token")
t("层归一化、QKV 投影与前馈网络都独立地作用于每一个 token，因此它们既不关心也不需要知道某个 token 属于哪个请求，可以在整条扁平流上以满效率跑一次。但注意力不能这样工作：一个 token 只能注意到它自己这个请求里更早的 token，而每个请求的 KV cache 长度各不相同。所以扁平张量会在注意力边界处被切开，注意力针对每个请求、对着它自己的缓存分别执行，输出再合并回这条流，进入下一个可批处理的算子。")
fig("fig10.jpg","图 10：选择性批处理：层归一化、QKV 投影与前馈网络跑在同一条扁平 token 流上，注意力则按请求切开、各自对着自己的 KV cache 执行，再合并回这条流")
h2("一次调度步骤：四步讲清")
t("在两轮前向传播之间，调度器回答一个问题：接下来哪些请求运行、每个请求拿到多少 token。它用四步回答这个问题，这里以 vLLM 的 V1 调度器作为参考实现。")
fig("fig13.jpg","图 13：调度器在四步内决定这一轮哪些请求运行、各拿多少 token")
t("第一步，先为这一步固定一个预算：max_num_batched_tokens 限定这一步最多可以发出多少 token；max_num_seqs 限定同时最多有多少条序列在飞。")
t("第二步，正在运行的请求先来认领计算预算。每个请求都带着一个「已经算过多少 token」的计数和一个目标计数，调度器发放 token，用来缩短请求当前所在位置与它想要到达位置之间的差距，并随着发放扣减预算。")
t("这里调度器本可以合理地保留两条代码路径：一条给 prefill，一条给 decode，因为 prefill 处理整个提示词、decode 只产出一个 token。但在实践中并没有这种切分：prefill 与 decode 看起来是两种不同的活，可调度器看到的是同一个数字——取目标值、减去已经算好的、在预算允许时发出这么多 token。")
fig("fig14.jpg","图 14：prefill 与 decode 在调度器眼里是同一个数字运算")
t("于是一条全新的 4,096 token 提示词，这个数字就是 4,096；一个生成到一半的请求，这个数字就是 1。两种情况走的是同一行代码。")
fig("fig15.jpg","图 15：分块 prefill 与前缀缓存同样不需要额外处理")
t("分块 prefill 与前缀缓存也不需要额外处理：如果一条 4,096 token 的提示词塞不进预算，调度器这一轮先发 2,048、下一轮再发另外 2,048；如果这 4,096 个 token 里有 3,000 个来自更早请求的缓存，那就只剩 1,096 个需要发出。")
t("__CODE__python::# simplified from vllm/v1/core/sched/scheduler.py\ntokens_this_step = min(\n    request.num_tokens_with_spec - request.num_computed_tokens,\n    remaining_token_budget,\n)")
t("第三步，调度器为刚刚分配的 token 认领 KV 块。它是在做决定的过程中预留这块内存，而不是决定完之后才去要。一步只有在缓存装得下它产出的内容时才成立，所以当空闲块不够时，调度器会从运行列表里最新的那个请求手中把它们拿走。")
t("第四步，剩下的预算给等待中的请求。那些还没开始的请求，用剩下的 token 被调度进来；如果运行中的请求已经把预算用光，这一步就不会有新请求启动。之后，调度器交给 GPU 一份清单：每个请求这一轮跑多少 token，以及把这些 token 写进哪些 KV 块。")

h2("Token 预算同时决定延迟与吞吐")
t("一步的耗时等于它内部 token 的数量，这让 max_num_batched_tokens 既是一个吞吐设置，也是一个延迟设置。")
t("补充说明一下这个概念：max_num_batched_tokens 是调度器在一次前向传播里可以放入的 token 总数，按这一步里所有请求累加，它不是单个请求的上限。一个解码请求只贡献一个 token，因为它只产出一个；一次 prefill 贡献多少个提示词 token，取决于调度器发给它多少。")
t("大约在 2,048 这个量级时，没有任何一步会跑得很长，于是 token 间延迟保持得很紧，但 GPU 常常吃不饱；大约在 16,384 时，GPU 保持饱和、吞吐上升，但 batch 里的每个请求都要等一个更长的步。")
t("这个预算设置控制的不只是大小。开启分块 prefill（这是 V1 在可能的场合下的默认行为）后，调度器会先用待处理的 decode 填满预算，再把剩下的给 prefill，塞不下的 prefill 就被切成块。")

h2("抢占：为什么同一段 prefill 要算两遍")
t("当块分配失败时，调度器会释放某个运行中请求的块、把它标记为被抢占、把它的 num_computed_tokens 归零、清掉它的投机 token，再把它放回等待队列的最前面。")
t("归零是真实存在的成本：假设一个请求已经 prefill 了 3,900 个 token，它回来时这些全都没被保存下来，就必须把 3,900 个 token 重新算一遍。V1 把重算变成了默认的抢占模式，并把更早的交换（swap）路径整个去掉了。")
t("从外部看，这很像 GPU 没有余量了：延迟随着流量上升而攀升，加副本看起来是解决办法。")
fig("fig16.jpg","图 16：抢占导致同一段 prefill 被反复重算")
t("实际发生的是同一段 prefill 被算了两三遍：请求被抢占、被重新接纳、再被抢占，每一次循环都在重复 GPU 早就完成的工作。vLLM 把它统计在 Prometheus 的 total_cumulative_preemption_cnt 里，当 p99 在流量没有变化的情况下攀升时，这是第一个应该看的指标。")
t("补充一下 p99 的含义：它是你最慢的那 1% 请求所经历的延迟。平均值会掩盖抢占，因为大多数请求永远不会被抢占，问题总是出现在尾部。有三个设置可以改善它：提高 gpu_memory_utilization，让更多显存变成 KV cache；降低 max_num_seqs，让竞争这块内存的序列更少；提高 tensor_parallel_size，让权重分散到多张 GPU 上，从而给每张设备留下更多余量。")
fig("fig17.jpg","图 17：三个可调设置——提高显存利用率、降低并发序列数、提高张量并行度")

h2("收尾：先看调度器，再看模型")
t("以上所有内容最终归结为一个循环：调度器在每一轮前向传播里重建 batch、按固定预算发放 token、并在做决定的同时预留 KV 块。这三步动作，决定了你的 GPU 实际产出多少。")
t("Anyscale 在 OPT-13B 上的基准显示：随着输出长度变得参差，静态批处理会掉到大约 81 tokens/s，而 vLLM 在同一块 A100 上达到了朴素 Hugging Face 服务的 23 倍吞吐。这些提升没有一个来自更快的模型。")
t("所以如果你的问题是吞吐或 p99，在动模型之前，先看调度器这一层。抢占计数器通常是最便宜的起点，因为它用一个数字就告诉你：你的 KV 池是否匹配你所配置的并发量。")

