t("需要强调的是，这些目标本身往往互相冲突：提高加载/存储发射率通常需要更强的跨核并行，这又要求更小的 tile；而更小的 tile 会降低缓存层级中的数据复用，因为复用与 tile 尺寸紧密相关。解析模型正是通过估计总延迟来在这些取舍之间导航。")

h3("量化 GEMM 延迟")
t("最后，所有参数被聚合成一个最终的「延迟」，作为某个分块方案质量的量化指标。需要考虑流水线同时受内存加载与计算指令延迟中较大者的限制，还要考虑额外的流水线气泡：开头「只有加载没有计算」的气泡称为 prologue，结尾「只写不计算」的称为 epilogue。prologue 的规模与软件流水线的加载阶段相同，但 store 阶段只随输出 tile 的尺寸伸缩，而不是随输入 tile 尺寸。与 K 方向上每一次迭代都会产生的流水线延迟不同，prologue 与 epilogue 每个输出 tile 只发生一次。")
t("由于计算可能被暴露到多个时间步（当输出 tile 数量超过计算单元数量时），每个时间步的延迟等于单个输出 tile 的延迟，再乘以时间步数，就得到整个 GEMM 运算的总延迟。")

