h3("三个维度分别解决什么问题")
t("更大的语料通过引入困难负例，让基准更有区分度：那些语义上与查询相似、但并未提供所需信息的文档，检索器必须把这种「看起来可能相关」与真正相关区分开。反过来，如果缩小语料但保留已知相关文档，就会把这些干扰项删掉、抬高召回率，作者做的子采样实验也显示了这一点。")
t("更多已判定查询让性能估计更可靠：查询集太小，基准结果会严重依赖抽样到了哪些查询，既难以精确估计每个模型的性能，也难以有把握地区分模型之间的差距。更深的判定则减少评估中的假阴性：标签稀疏时，检索器可能检索到相关但未被判定的文档，从而被错误地算作不相关，让评估变得不可靠。信息检索领域主要的大规模开放数据集 MS MARCO 就是例子——那里人工检查过的「被检索到但未标注」的前排段落中，有 70% 实际上是相关的。")
t("现有基准往往只在一到两个维度上扩展：网页规模的集合通常已判定查询很少，而查询很多的基准一般语料小得多、标签也稀疏。更关键的是，大多数基准使用人写的查询，而 agentic RAG 系统用的是 agent 重新表述过的查询，两者在措辞、结构与具体程度上都可能不同。Q2D-Web 三个维度同时扩展：1.9 亿份文档、69,721 条 agent 重写查询、合并判定集里平均每条查询 99.6 个正相关判定。最接近的公开对照是 MS MARCO Web Search：1.009 亿文档、9,374 条测试查询，每条查询只有一个由点击推导出的正标签。")

