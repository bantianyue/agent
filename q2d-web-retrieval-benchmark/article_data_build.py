h3("判定")
t("在大规模下，相关性标签天然是不完整的：为所有可能的查询-文档对打标并不可行，而每一个判定来源都带有不同的偏差。Q2D-Web 因此使用三套相关性集合，而不是把某一个来源当成标准答案，从而在不承受单一偏差的前提下提高标注深度。")
t("引用标签：当 agent 在某次回答中引用了某份文档，就把该文档标为相关。这是最接近下游使用的信号——agent 把它选作某个论断的证据；但引用在构造上就是高精度、低召回：一旦 agent 已有足够支撑，它就没有理由再去引用其他每一份相关页面。")
t("网页排名标签：每条查询包含最多 50 份文档（平均 43.1 份），由内部检索栈在第一阶段用 BM25 与稠密检索识别，随后经交叉编码器重排。它捕捉的是有用但未被引用的文档。")
t("合并加 LLM 判定：取引用与网页排名的并集，再为此前未判定的候选补充 LLM 判定，目标是减少假阴性的数量。具体做法是汇集 BM25、ColBERTv2 以及七个在 2025 年 1 月 1 日之前发布的稠密检索器的结果，用倒数排名融合（RRF）合并它们的排名，选出前 500 份未判定文档，再用 DeepSeek-V4-Flash 做严格的二分类相关性评判。")
t("这三套集合让我们可以追问：模型表现是否依赖于「相关性」如何被定义。它们也减少了对单一标注栈的依赖，否则这套栈可能会偏向与生成标签所用系统相似的检索器。")
