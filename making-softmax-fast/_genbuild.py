t("所以有效字节数没有变化，变化的是这些字节通过内存系统的效率。回想 GEMV 那一章的内存事务效率：当一个线程独占一行时，warp 从内存系统请求 1024 字节，却只用到其中 128 字节，效率只有 12.5%；而当一个 warp 横跨一行读取时，同样的 128 个有用字节只占四个 32 字节扇区，效率是 1。在这个简化的事务模型下，有效流量从 12MN/(1/8) = 96MN 字节降到 12MN/1 = 12MN 字节，内存事务效率最多提升 8 倍。不过别急着下结论：这不代表 kernel 一定会快 8 倍，缓存命中、对齐、行长、指数运算与归约工作都会影响最终运行时间。要点在于，我们不再把每 8 个被搬运的字节里有 7 个白白扔掉。忽略不大的归约开销，有效算术强度从大约 4MN/96MN = 1/24 ≈ 0.0417 FLOPs/byte 提升到大约 4MN/12MN = 1/3 ≈ 0.333 FLOPs/byte。我们没有改变 Softmax 的理论算术强度，只是不再让糟糕的访问模式把它的有效算术强度压低。")
t("再看计算与通信——归约当然不是免费的。设 warp 大小为 W = 32：求行最大值需要 W−1 = 31 次比较；校正局部分母需要 W 次减法、W 次指数求值与 W 次乘法；归约校正后的分母需要 W−1 = 31 次加法。因此每行的普通浮点开销是 (W + W + W−1) = 3W−1 次浮点运算，乘以 M 行就是 M(3W−1) 次额外浮点运算，另外还有 MW 次额外的指数求值。对包含成百上千个元素的行来说，这点固定工作量相比全部 MN 个元素的工作量很小。")
